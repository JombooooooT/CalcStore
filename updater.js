/* =========================================================
   CalcStore — Auto-Updater (main process)
   Wraps electron-updater with a user-controlled flow:
   the app checks on demand, the user chooses to download,
   and the user chooses when to restart & install.
   ========================================================= */

const { app } = require('electron');
const { autoUpdater } = require('electron-updater');

const STATUS_CHANNEL = 'update:status';

let windowGetter = () => null;
let lastStatus = { state: 'idle' };
let initialized = false;
let checkInFlight = false;

function currentVersion() {
  return app.getVersion();
}

// electron-updater may hand us releaseNotes as a plain string (GitHub releases)
// or as an array of { version, note } entries. Normalise both to a single string
// so the renderer can safely render it as plain text.
function normalizeReleaseNotes(notes) {
  if (!notes) return null;
  if (Array.isArray(notes)) {
    const joined = notes
      .map((entry) => {
        if (!entry) return '';
        if (typeof entry === 'string') return entry;
        const heading = entry.version ? 'v' + entry.version + '\n' : '';
        return heading + (entry.note || '');
      })
      .filter(Boolean)
      .join('\n\n');
    return joined || null;
  }
  const text = String(notes).trim();
  return text || null;
}

function broadcast(status) {
  lastStatus = status;
  const win = windowGetter();
  if (win && !win.isDestroyed()) {
    win.webContents.send(STATUS_CHANNEL, status);
  }
}

// electron-updater only works inside an installed (packaged) build,
// because it reads the app-update.yml generated by electron-builder.
function unsupportedStatus() {
  if (app.isPackaged) return null;
  return {
    state: 'unsupported',
    current: currentVersion(),
    message: 'Updates are available only in the installed build.',
  };
}

function init(getWindow) {
  if (initialized) return;
  initialized = true;
  windowGetter = typeof getWindow === 'function' ? getWindow : () => null;

  // User-controlled: never download or install without an explicit request.
  autoUpdater.autoDownload = false;
  autoUpdater.autoInstallOnAppQuit = true;
  autoUpdater.logger = console;

  autoUpdater.on('checking-for-update', () => {
    broadcast({ state: 'checking', current: currentVersion() });
  });

  autoUpdater.on('update-available', (info) => {
    broadcast({
      state: 'available',
      current: currentVersion(),
      version: info && info.version ? String(info.version) : null,
      releaseName: (info && info.releaseName) || null,
      releaseNotes: normalizeReleaseNotes(info && info.releaseNotes),
    });
  });

  autoUpdater.on('update-not-available', () => {
    broadcast({ state: 'up-to-date', current: currentVersion() });
  });

  autoUpdater.on('download-progress', (progress) => {
    broadcast({
      state: 'downloading',
      percent: Math.max(0, Math.min(100, Math.round((progress && progress.percent) || 0))),
      transferred: (progress && progress.transferred) || 0,
      total: (progress && progress.total) || 0,
      bytesPerSecond: (progress && progress.bytesPerSecond) || 0,
    });
  });

  autoUpdater.on('update-downloaded', (info) => {
    broadcast({
      state: 'downloaded',
      current: currentVersion(),
      version: info && info.version ? String(info.version) : null,
      releaseNotes: normalizeReleaseNotes(info && info.releaseNotes),
    });
  });

  autoUpdater.on('error', (err) => {
    broadcast({
      state: 'error',
      current: currentVersion(),
      message: err && err.message ? String(err.message) : 'Update error',
    });
  });

  lastStatus = { state: 'idle', current: currentVersion() };
}

async function check() {
  const unsupported = unsupportedStatus();
  if (unsupported) {
    broadcast(unsupported);
    return { ok: true, status: unsupported };
  }
  if (checkInFlight) {
    return { ok: true, status: lastStatus };
  }

  checkInFlight = true;
  broadcast({ state: 'checking', current: currentVersion() });
  try {
    await autoUpdater.checkForUpdates();
    return { ok: true, status: lastStatus };
  } catch (err) {
    const status = {
      state: 'error',
      current: currentVersion(),
      message: err && err.message ? String(err.message) : 'Update check failed',
    };
    broadcast(status);
    return { ok: false, status };
  } finally {
    checkInFlight = false;
  }
}

async function download() {
  const unsupported = unsupportedStatus();
  if (unsupported) {
    broadcast(unsupported);
    return { ok: false, status: unsupported };
  }

  try {
    await autoUpdater.downloadUpdate();
    return { ok: true, status: lastStatus };
  } catch (err) {
    const status = {
      state: 'error',
      current: currentVersion(),
      message: err && err.message ? String(err.message) : 'Download failed',
    };
    broadcast(status);
    return { ok: false, status };
  }
}

function install() {
  const unsupported = unsupportedStatus();
  if (unsupported) {
    broadcast(unsupported);
    return { ok: false, status: unsupported };
  }

  // Defer so the IPC reply reaches the renderer before the app quits.
  setImmediate(() => {
    autoUpdater.quitAndInstall(false, true);
  });
  return { ok: true, status: { state: 'installing', current: currentVersion() } };
}

function getStatus() {
  return unsupportedStatus() || lastStatus;
}

module.exports = {
  STATUS_CHANNEL,
  init,
  check,
  download,
  install,
  getStatus,
  currentVersion,
};
